#!/usr/bin/env node
// ---------------------------------------------------------------------------
// npm run bait:shader
//
// Writes a page that COMPILES systems/baitShimmer.js's injected GLSL against a
// real driver and prints the driver's own error log — then, if a browser is
// available, drives it and reports here.
//
// WHY THIS EXISTS SEPARATELY FROM npm run test:bait. Node cannot see a GLSL
// error. tools/bait-ball-test.mjs runs the whole flock, the noise, the ledger
// and the exchange without ever compiling a line of shader, and it passes
// cheerfully with a shimmer that never built. And the failure is not a
// wrong-looking fish: `customProgramCacheKey` pins every shimmering material to
// ONE program, so a syntax error anywhere in here means every fish in every
// bait ball renders as nothing, with the only trace a console line behind a
// game that still runs. See tools/biolum-shader-check.mjs, whose header records
// that exact thing happening once already.
//
// THE CONTEXT MUST BE WEBGL2, because that is what three 0.183 requires and
// therefore what the game runs on. Not a formality: these are GLSL ES 1.00
// shaders and several conveniences (`fwidth` among them) are extensions there
// rather than core, so a naive WebGL1 check reports errors players could never
// hit and misses ones they would.
//
//   node --import ./tools/vite-loader.mjs tools/bait-shader-check.mjs [outDir]
//   → serve that directory over http and open it (file:// will not execute)
// ---------------------------------------------------------------------------

import './dom-stub.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NOISE_FIELD_GLSL } from '../path/src/systems/noiseGlsl.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(HERE, '..');

// Read as SOURCE rather than by calling the module, so this compiles the
// strings that ship rather than anything a module graph might have rewritten on
// the way past — and so a refactor that stops producing the injection fails
// here loudly rather than checking an empty string.
const src = fs.readFileSync(path.resolve(HERE, '../path/src/systems/baitShimmer.js'), 'utf8');

function between(open, close) {
  const a = src.indexOf(open);
  if (a < 0) { console.error(`could not find ${JSON.stringify(open)} in baitShimmer.js`); process.exit(1); }
  const from = a + open.length;
  const b = src.indexOf(close, from);
  if (b < 0) { console.error(`could not find the close of ${JSON.stringify(open)}`); process.exit(1); }
  return src.slice(from, b);
}

// The two injections, pulled out of the replace() calls that install them.
// Template literals, so `${MAX_SHIMMER_BALLS}` and `${NOISE_FIELD_GLSL}` are
// still holes — filled here with the same values the module fills them with.
const MAX = Number(/MAX_SHIMMER_BALLS = (\d+)/.exec(src)?.[1] ?? 8);
const declRaw = between("      .replace('#include <common>', `#include <common>\n", '`)\n');
const bodyRaw = between("      .replace('#include <map_fragment>', `#include <map_fragment>\n", '`);\n');

const fill = (t) => t
  .replaceAll('${MAX_SHIMMER_BALLS}', String(MAX))
  .replaceAll('${NOISE_FIELD_GLSL}', NOISE_FIELD_GLSL);

// three's prelude cut to what this actually references, and kept explicit: the
// point is what the DRIVER thinks, and a prelude generated by the same library
// that generated the shader can hide a mismatch between them.
const fragment = `precision highp float;
#define PI 3.141592653589793
${fill(declRaw)}
void main() {
  // Everything the injection reads that three declares for real. diffuseColor
  // is the one that matters — leave it out and this fails on a line the game
  // compiles fine.
  vec4 diffuseColor = vec4(1.0);
  gl_FragColor = vec4(0.0);
${fill(bodyRaw)}
  gl_FragColor = diffuseColor;
}
`;

// The vertex half is two one-line splices, and the interesting one is the
// world-position write: it names `transformed` and `modelMatrix`, both of which
// exist only because three declares them, so a check that skipped the vertex
// stage would miss a rename in either.
const vertex = `precision highp float;
uniform mat4 modelMatrix;
uniform mat4 modelViewMatrix;
uniform mat4 projectionMatrix;
attribute vec3 position;
varying vec3 vBaitWorld;
void main() {
  vec3 transformed = position;
  vBaitWorld = (modelMatrix * vec4(transformed, 1.0)).xyz;
  gl_Position = projectionMatrix * modelViewMatrix * vec4(transformed, 1.0);
}
`;

const html = `<!doctype html><meta charset="utf-8"><title>bait shimmer shader check</title>
<body style="font:13px ui-monospace,monospace;background:#111;color:#ddd;padding:16px">
<pre id="out">compiling...</pre>
<script>
const SRC = ${JSON.stringify({ fragment, vertex })};
const gl = document.createElement('canvas').getContext('webgl2');
const lines = [];
let bad = 0;
function compile(kind, source, label) {
  const s = gl.createShader(kind);
  gl.shaderSource(s, source);
  gl.compileShader(s);
  if (gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    lines.push('ok   ' + label + ' compiles');
    return true;
  }
  bad++;
  const log = gl.getShaderInfoLog(s) || '';
  lines.push('FAIL ' + label + ' does NOT compile');
  for (const l of log.trim().split('\\n')) lines.push('       ' + l);
  const body = source.split('\\n');
  const seen = new Set();
  for (const m of log.matchAll(/ERROR: \\d+:(\\d+)/g)) {
    const n = +m[1];
    if (seen.has(n)) continue;
    seen.add(n);
    lines.push('');
    for (let i = Math.max(0, n - 3); i < Math.min(body.length, n + 2); i++) {
      lines.push((i === n - 1 ? '  >> ' : '     ') + String(i + 1).padStart(4) + '  ' + body[i]);
    }
  }
  return false;
}
if (!gl) {
  lines.push('no webgl2 context — nothing was checked, and the game needs one');
  bad++;
} else {
  compile(gl.VERTEX_SHADER, SRC.vertex, 'the shimmer vertex splice');
  compile(gl.FRAGMENT_SHADER, SRC.fragment, 'the shimmer fragment injection');
  lines.push('     every bait ball shares this one program, so this is all of them');
}
lines.push('');
lines.push(bad === 0 ? 'ALL GOOD' : bad + ' PROBLEM(S)');
document.getElementById('out').textContent = lines.join('\\n');
document.title = bad === 0 ? 'bait shimmer ok' : 'bait shimmer FAILED';
<\/script>
`;

const out = path.join(OUT_DIR, '.bait-shader-check.html');
fs.writeFileSync(out, html);
console.log(`wrote ${out}`);
console.log('serve that directory over http and open it — file:// will not execute.');
