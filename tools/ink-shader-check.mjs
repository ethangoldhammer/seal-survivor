#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Writes a standalone page that COMPILES the ink trail's shader against a real
// WebGL driver and prints the driver's own error log.
//
// Same reason as tools/impact-shader-check.mjs and the same shape. A Node
// harness can prove the simulation is right — tools/kraken-test.mjs does, down
// to the drag coefficient — and still sail straight past a GLSL error, which
// does not throw, does not warn, and simply renders nothing. On an effect whose
// entire job is to be a dark shape on dark water, "renders nothing" is not a
// failure anyone notices by looking.
//
// THIS SHADER HAS THREE EXTRA WAYS TO FAIL SILENTLY, and all are checked:
//
//   A VARYING THE VERTEX SIDE NEVER WRITES. `vWorld` carries the world position
//   the porthole is measured against. Declared on both sides and written on
//   neither, it compiles, links, and reads zero — which puts the seal's clear
//   circle permanently at the origin, i.e. in the middle of the arena, on every
//   frame of every fight.
//
//   AN ATTRIBUTE NOTHING SUPPLIES. `aAlpha` is per-INSTANCE and written by the
//   draw loop; a name that drifted between the geometry and the shader compiles
//   perfectly and reads zero, which means a cloud that is entirely transparent.
//
//   AN INSTANCE COUNT NOBODY SET. The geometry is sized to the particle cap and
//   the draw loop narrows it to the live count each frame. Left at zero it
//   compiles, links, uploads, and draws nothing whatsoever.
//
// The page touches nothing else: no dev server, no tuning file. It pulls the
// real shader strings off the real material, built by the real system.
//
//   node --import ./tools/vite-loader.mjs tools/ink-shader-check.mjs [out.html]
//   → serve the directory over http and open it (file:// will not run)
// ---------------------------------------------------------------------------

import './dom-stub.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { burstInk, updateInkTrail } from '../path/src/systems/inkTrail.js';

const scene = new THREE.Scene();
// Drive it the way a fight does — a moving source, then a burst — so the
// geometry carries real coordinates and real alphas rather than the zeros it is
// allocated with. A page that compiled a shader against an empty buffer would
// miss nothing about GLSL and everything about whether the draw loop ran.
const DT = 1 / 60;
for (let i = 0; i < 90; i++) {
  const t = i * DT;
  updateInkTrail(DT, scene, {
    x: Math.cos(t) * 12, y: Math.sin(t) * 12,
    vx: -Math.sin(t) * 12, vy: Math.cos(t) * 12,
  }, { x: 0, y: 0 }, true);
}
burstInk(1);
for (let i = 0; i < 20; i++) {
  updateInkTrail(DT, scene, { x: 12, y: 0, vx: 0, vy: 12 }, { x: 0, y: 0 }, true);
}

const group = scene.children.find((c) => c.name === 'inkTrail');
if (!group) {
  console.error('no inkTrail group — the system built nothing, so there is no shader to check');
  process.exit(1);
}
const mesh = group.children[0];

// three's own prefix, cut to what this shader actually references. Kept
// explicit rather than borrowed from the renderer: the point of this page is to
// be told what the DRIVER thinks, and a prefix generated by the same library
// that generated the shader can hide a mismatch between them.
// `instanceMatrix` is in the list because three INJECTS it for an InstancedMesh
// rather than the shader declaring it — so a hand-written prefix that omits it
// reports a perfectly good shader as broken, which is what this page did on its
// first run after the ribbon became a cloud of quads.
const PREFIX_VERT = `precision highp float;
uniform mat4 modelViewMatrix;
uniform mat4 projectionMatrix;
attribute vec3 position;
attribute mat4 instanceMatrix;
`;
const PREFIX_FRAG = `precision highp float;
`;

const vertexSrc = mesh.material.vertexShader;
const declared = [...vertexSrc.matchAll(/^\s*attribute\s+\w+\s+(\w+)\s*;/gm)].map((x) => x[1]);
const supplied = Object.keys(mesh.geometry.attributes);
// Varyings the fragment side reads, against the ones the vertex side assigns.
const varyings = [...mesh.material.fragmentShader.matchAll(/^\s*varying\s+\w+\s+(\w+)\s*;/gm)].map((x) => x[1]);
const written = varyings.filter((v) => new RegExp(`\\b${v}\\s*=`).test(vertexSrc));

const alpha = mesh.geometry.attributes.aAlpha.array;
// The per-INSTANCE transforms, not the shared unit quad. Measuring
// `attributes.position` here reports "1 unit across" however big the cloud is —
// it is one quad that every instance reuses.
const inst = mesh.instanceMatrix.array;

const info = {
  vertex: PREFIX_VERT + vertexSrc,
  fragment: PREFIX_FRAG + mesh.material.fragmentShader,
  missingAttributes: declared.filter((a) => a !== 'position' && !supplied.includes(a)),
  unwrittenVaryings: varyings.filter((v) => !written.includes(v)),
  uniforms: Object.keys(mesh.material.uniforms),
  // Proof the draw loop ran: a buffer of zeros means the simulation built
  // geometry and never filled it, which renders as nothing at all and would
  // otherwise look exactly like a shader that failed to compile.
  liveAlphas: [...alpha].filter((v) => v > 0.001).length,
  totalAlphas: alpha.length,
  instanceCount: mesh.count,
  spread: (() => {
    // Column 3 of each 4x4 is its translation; x lives at offset 12.
    let min = Infinity;
    let max = -Infinity;
    for (let i = 0; i < mesh.count; i++) {
      const x = inst[i * 16 + 12];
      min = Math.min(min, x);
      max = Math.max(max, x);
    }
    return Number.isFinite(min) ? +(max - min).toFixed(2) : 0;
  })(),
  // The two states the material must be in for ink to occlude rather than glow.
  blending: mesh.material.blending === THREE.NormalBlending ? 'normal' : `NOT NORMAL (${mesh.material.blending})`,
  depthTest: mesh.material.depthTest,
  renderOrder: mesh.renderOrder,
};

const OUT = process.argv[2] ?? path.join(
  path.dirname(fileURLToPath(import.meta.url)), '../.ink-shader-check.html',
);

const html = `<!doctype html><meta charset="utf-8"><title>ink trail shader check</title>
<body style="font:13px ui-monospace,monospace;background:#111;color:#ddd;padding:16px">
<pre id="out">compiling...</pre>
<script>
const C = ${JSON.stringify(info)};
const gl = document.createElement('canvas').getContext('webgl');
const lines = [];
let bad = 0;

function compile(label, type, src) {
  const s = gl.createShader(type);
  gl.shaderSource(s, src);
  gl.compileShader(s);
  if (gl.getShaderParameter(s, gl.COMPILE_STATUS)) { lines.push('  ok   ' + label); return s; }
  bad++;
  lines.push('  FAIL ' + label);
  for (const l of (gl.getShaderInfoLog(s) || '').trim().split('\\n')) lines.push('         ' + l);
  return null;
}

function check(label, cond, detail) {
  if (!cond) bad++;
  lines.push('  ' + (cond ? 'ok  ' : 'FAIL') + ' ' + label + (detail ? '  — ' + detail : ''));
}

if (!gl) {
  lines.push('no webgl context — nothing was checked');
  bad++;
} else {
  lines.push('the shader, against this machine\\'s driver');
  const v = compile('vertex shader', gl.VERTEX_SHADER, C.vertex);
  const f = compile('fragment shader', gl.FRAGMENT_SHADER, C.fragment);
  if (v && f) {
    // LINKED, not just compiled. A varying declared differently on the two
    // sides compiles cleanly on both and fails only here.
    const p = gl.createProgram();
    gl.attachShader(p, v); gl.attachShader(p, f); gl.linkProgram(p);
    if (gl.getProgramParameter(p, gl.LINK_STATUS)) lines.push('  ok   program links');
    else {
      bad++;
      lines.push('  FAIL program links');
      for (const l of (gl.getProgramInfoLog(p) || '').trim().split('\\n')) lines.push('         ' + l);
    }
  }

  lines.push('');
  lines.push('the silent failures');
  check('every attribute the shader declares is supplied',
    C.missingAttributes.length === 0, C.missingAttributes.join(', ') || 'all supplied');
  check('every varying the fragment side reads is written by the vertex side',
    C.unwrittenVaryings.length === 0,
    C.unwrittenVaryings.length ? C.unwrittenVaryings.join(', ') + ' read zero — the porthole would sit at the origin' : 'all written');

  lines.push('');
  lines.push('the draw loop actually filled the buffers');
  check('some instances carry a non-zero alpha', C.liveAlphas > 0,
    C.liveAlphas + ' of ' + C.totalAlphas + ' allocated');
  check('the draw count was narrowed to the live particles', C.instanceCount > 0,
    C.instanceCount + ' instances drawn');
  check('and the cloud has real extent', C.spread > 1, C.spread + ' units across');

  lines.push('');
  lines.push('the material is set up to OCCLUDE rather than glow');
  check('blending is normal, not additive', C.blending === 'normal', C.blending);
  check('depthTest is off, so a cloud covers creatures in any depth lane', C.depthTest === false, String(C.depthTest));
  check('and it draws above the particles (10)', C.renderOrder > 10, 'renderOrder ' + C.renderOrder);

  lines.push('');
  lines.push('uniforms: ' + C.uniforms.join(', '));
}

lines.push('');
lines.push(bad === 0 ? 'ALL PASS' : bad + ' PROBLEM(S)');
document.getElementById('out').textContent = lines.join('\\n');
document.title = bad === 0 ? 'ink shader OK' : 'ink shader ' + bad + ' PROBLEM(S)';
window.__done = true;
window.__bad = bad;
</script>`;

fs.writeFileSync(OUT, html);
console.log(`wrote ${OUT}`);
console.log('serve the directory over http and open it — file:// will not run a shader compile.');
