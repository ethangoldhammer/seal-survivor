#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Writes a page that COMPILES systems/boostAura.js's fragment shader against a
// real driver and prints the driver's own error log.
//
// A GLSL error here renders NOTHING and throws NOTHING: the shell simply never
// appears, every Node harness in this repo goes on passing, and the only trace
// is a console line behind a game that still runs. This shader splices in a
// SHARED string — WISP_GLSL, which systems/water.js and systems/graveBeam.js
// also carry — so a stray backtick in a comment over there cuts the template in
// half over here, and the syntax error points at the comment rather than at the
// backtick. See npm run test:goofx, which exists for the same failure.
//
// THE CONTEXT MUST BE WEBGL2, because that is what three 0.183 requires and
// therefore what the game runs on. Not a formality: these are GLSL ES 1.00
// shaders and `fwidth` is an extension rather than core there, so a naive
// WebGL1 check reports errors players could never hit and misses ones they can.
//
//   node --import ./tools/vite-loader.mjs tools/aura-shader-check.mjs [outDir]
//   → serve that directory over http and open it (file:// will not execute)
// ---------------------------------------------------------------------------

import './dom-stub.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { AURA_VERTEX_GLSL, AURA_FRAGMENT_GLSL, AURA_UNIFORM_NAMES } from '../path/src/systems/boostAura.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(HERE, '..');

// THE TEMPLATE SURVIVED. A backtick inside a GLSL comment ends the literal and
// the rest of the shader becomes JavaScript; when the two halves happen to be
// valid JS on their own, nothing complains and the shader is simply short.
const tail = 'gl_FragColor = vec4(uColor * uStrength * a, a);';
if (!AURA_FRAGMENT_GLSL.includes(tail)) {
  console.error('the fragment template was cut short — the last line is missing.');
  console.error('look for a backtick inside a comment in boostAura.js or wispGlsl.js.');
  process.exit(1);
}
// ...and the shared noise really was spliced in, rather than the import
// resolving to an empty string and leaving every wisp() call undeclared.
if (!AURA_FRAGMENT_GLSL.includes('float wisp(')) {
  console.error('WISP_GLSL did not make it into the fragment shader.');
  process.exit(1);
}
// EVERY UNIFORM THE CPU WRITES IS DECLARED AND READ. A uniform the shader
// never mentions is optimised out, the upload silently does nothing, and the
// knob for it in the tuner moves a number nobody looks at.
let bad = 0;
for (const name of AURA_UNIFORM_NAMES) {
  const decl = new RegExp(`uniform\\s+\\w+\\s+${name}\\s*;`).test(AURA_FRAGMENT_GLSL);
  const uses = AURA_FRAGMENT_GLSL.split(name).length - 1;
  if (!decl) { console.error(`FAIL ${name} is uploaded but never declared`); bad++; }
  else if (uses < 2) { console.error(`FAIL ${name} is declared but never read`); bad++; }
}
if (bad) process.exit(1);
console.log(`ok   the template survived, and all ${AURA_UNIFORM_NAMES.length} uniforms are declared and read`);

// three's prelude, cut to what these strings actually reference and kept
// explicit: the point is what the DRIVER thinks, and a prelude generated by the
// same library that generated the shader can hide a mismatch between them.
const vertex = `precision highp float;
uniform mat4 projectionMatrix;
uniform mat4 modelViewMatrix;
attribute vec3 position;
attribute vec2 uv;
${AURA_VERTEX_GLSL}`;
const fragment = `precision highp float;
${AURA_FRAGMENT_GLSL}`;

const html = `<!doctype html><meta charset="utf-8"><title>boost aura shader check</title>
<body style="font:13px ui-monospace,monospace;background:#111;color:#ddd;padding:16px">
<pre id="out">compiling...</pre>
<script>
const SRC = ${JSON.stringify({ vertex, fragment })};
const gl = document.createElement('canvas').getContext('webgl2');
const lines = [];
let bad = 0;
function compile(kind, label, src) {
  const s = gl.createShader(kind);
  gl.shaderSource(s, src);
  gl.compileShader(s);
  if (gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    lines.push('ok   the boost aura ' + label + ' shader compiles');
    return s;
  }
  bad++;
  const log = gl.getShaderInfoLog(s) || '';
  lines.push('FAIL the boost aura ' + label + ' shader does NOT compile');
  for (const l of log.trim().split('\\n')) lines.push('       ' + l);
  const body = src.split('\\n');
  const seen = new Set();
  for (const m of log.matchAll(/ERROR: \\d+:(\\d+)/g)) {
    const n = +m[1];
    if (seen.has(n)) continue;
    seen.add(n);
    lines.push('');
    for (let i = Math.max(0, n - 3); i < Math.min(body.length, n + 2); i++) {
      lines.push((i === n - 1 ? '  >> ' : '     ') + String(i + 1).padStart(4) + '  ' + body[i]);
    }
  }
  return null;
}
if (!gl) {
  lines.push('no webgl2 context — nothing was checked, and the game needs one');
  bad++;
} else {
  const v = compile(gl.VERTEX_SHADER, 'vertex', SRC.vertex);
  const f = compile(gl.FRAGMENT_SHADER, 'fragment', SRC.fragment);
  // LINKED, not just compiled. A varying the two halves disagree about passes
  // both compiles and fails here, which is the whole reason this pairs them.
  if (v && f) {
    const p = gl.createProgram();
    gl.attachShader(p, v); gl.attachShader(p, f); gl.linkProgram(p);
    if (gl.getProgramParameter(p, gl.LINK_STATUS)) {
      lines.push('ok   ...and the two link');
    } else {
      bad++;
      lines.push('FAIL the program does not link');
      for (const l of (gl.getProgramInfoLog(p) || '').trim().split('\\n')) lines.push('       ' + l);
    }
  }
}
lines.push('');
lines.push(bad === 0 ? 'ALL GOOD' : bad + ' PROBLEM(S)');
document.getElementById('out').textContent = lines.join('\\n');
document.title = bad === 0 ? 'aura shader ok' : 'aura shader FAILED';
<\/script>
`;

const out = path.join(OUT_DIR, '.aura-shader-check.html');
fs.writeFileSync(out, html);
console.log(`wrote ${out}`);
console.log('serve that directory over http and open it — file:// will not execute.');
