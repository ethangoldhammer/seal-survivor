#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Writes a page that COMPILES systems/biolumSkin.js's injected GLSL against a
// real driver and prints the driver's own error log.
//
// This one earns its place more than the others. Every bioluminescent creature
// in the game shares ONE compiled program — customProgramCacheKey pins it to
// 'bioSkin' so a school of forty costs one compile — which means a syntax error
// anywhere in this shader does not produce a wrong-looking fish. It produces no
// fish: the seal, the lanternfish, both crabs, the escort squad and the boss
// all render as nothing, and the only trace is a console line behind a game
// that still runs. The file's own header says this happened once already.
//
// Node cannot see it. `npm test` exercises the uniforms, the presets and the
// bakes, and passes cheerfully with a shader that never compiled.
//
// THE CONTEXT MUST BE WEBGL2, because that is what three 0.183 requires and
// therefore what the game runs on. It is not a formality: these are GLSL ES
// 1.00 shaders, and `fwidth` — which an earlier version of the wireframe
// pattern used — is an extension there rather than core, so it fails on both
// WebGL1 and WebGL2 while a naive WebGL1 check reports errors players could
// never hit.
//
//   node --import ./tools/vite-loader.mjs tools/biolum-shader-check.mjs [outDir]
//   → serve that directory over http and open it (file:// will not execute)
// ---------------------------------------------------------------------------

import './dom-stub.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT_DIR = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(HERE, '..');

// Read as SOURCE rather than imported, so this compiles the strings that ship
// rather than anything a module graph might have rewritten on the way past.
const src = fs.readFileSync(path.resolve(HERE, '../path/src/systems/biolumSkin.js'), 'utf8');
const between = (a0, b0) => {
  const a = src.indexOf(a0);
  if (a < 0) { console.error(`could not find ${a0} in biolumSkin.js`); process.exit(1); }
  const from = a + a0.length;
  return src.slice(from, src.indexOf(b0, from));
};

// three's prelude, cut to what these two strings actually reference, and kept
// explicit: the point is what the DRIVER thinks, and a prelude generated by the
// same library that generated the shader can hide a mismatch between them.
const fragment = `precision highp float;
#define PI 3.141592653589793
${between('const GLSL = `', '\n`;')}
void main() {
  vec4 diffuseColor = vec4(1.0);
  gl_FragColor = vec4(0.0);
${between('const FRAG_BODY = `', '\n`;')}
}
`;

const html = `<!doctype html><meta charset="utf-8"><title>biolum shader check</title>
<body style="font:13px ui-monospace,monospace;background:#111;color:#ddd;padding:16px">
<pre id="out">compiling...</pre>
<script>
const SRC = ${JSON.stringify({ fragment })};
const gl = document.createElement('canvas').getContext('webgl2');
const lines = [];
let bad = 0;
if (!gl) {
  lines.push('no webgl2 context — nothing was checked, and the game needs one');
  bad++;
} else {
  const s = gl.createShader(gl.FRAGMENT_SHADER);
  gl.shaderSource(s, SRC.fragment);
  gl.compileShader(s);
  if (gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    lines.push('ok   the biolumSkin fragment shader compiles');
    lines.push('     every glowing creature shares this one program, so this is all of them');
  } else {
    bad++;
    const log = gl.getShaderInfoLog(s) || '';
    lines.push('FAIL the biolumSkin fragment shader does NOT compile');
    for (const l of log.trim().split('\\n')) lines.push('       ' + l);
    // A GLSL error is a line number and nothing else, so show the source there.
    const body = SRC.fragment.split('\\n');
    const seen = new Set();
    for (const m of log.matchAll(/ERROR: \\d+:(\\d+)/g)) {
      const n = +m[1];
      if (seen.has(n)) continue;
      seen.add(n);
      lines.push('');
      for (let i = Math.max(0, n - 3); i < Math.min(body.length, n + 2); i++) {
        lines.push((i === n - 1 ? '  >> ' : '     ') + String(i + 1).padStart(4) + '  ' + body[i]);
      }
    }
  }
}
lines.push('');
lines.push(bad === 0 ? 'ALL GOOD' : bad + ' PROBLEM(S)');
document.getElementById('out').textContent = lines.join('\\n');
document.title = bad === 0 ? 'biolum shader ok' : 'biolum shader FAILED';
<\/script>
`;

const out = path.join(OUT_DIR, '.biolum-shader-check.html');
fs.writeFileSync(out, html);
console.log(`wrote ${out}`);
console.log('serve that directory over http and open it — file:// will not execute.');
