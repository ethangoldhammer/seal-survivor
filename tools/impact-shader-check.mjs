#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Writes a standalone page that COMPILES the boss impact effect's three
// shaders against a real WebGL driver and prints the driver's own error log.
//
// Same reason as tools/grid-shader-check.mjs, and the same shape. A Node
// harness can check that every uniform is supplied and that the numbers
// reaching them are right, and still sail straight past a GLSL type error —
// which does not throw, does not warn, and simply renders nothing. On an
// impact effect that failure mode is invisible until somebody notices the
// game got quieter.
//
// These three are worth their own page because they are all INSTANCED, and an
// instanced shader has a second way to fail silently: a per-instance attribute
// the vertex shader declares but nothing ever supplies compiles perfectly and
// reads zero, which for `aLife` means every instance is permanently dead.
// So the page checks the declared attributes against the geometry too.
//
// The page touches nothing else: no dev server, no tuning file. It pulls the
// real shader strings off the real materials and hands them to the driver.
//
//   node --import ./tools/vite-loader.mjs tools/impact-shader-check.mjs [out.html]
//   → serve the directory over http and open it (file:// will not run)
// ---------------------------------------------------------------------------

import './dom-stub.mjs';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { initBossImpacts, spawnBossImpact, updateBossImpacts } from '../path/src/systems/bossImpact.js';

const scene = new THREE.Scene();
initBossImpacts(scene);
const group = scene.children.find((c) => c.isGroup);

// In the order initBossImpacts adds them: rings, shards, wounds.
//
// THE BOSS WEAK SPOTS ARE NOT HERE, and it is worth saying why rather than
// leaving the gap. They are painted by a MeshBasicMaterial patched through
// onBeforeCompile (systems/bossHotSpots.js), so there is no shader SOURCE to
// hand a driver until a real renderer has expanded three's chunks for the
// object it is drawn on — which is a skinned boss. Their instrument is the
// look page, `npm run looks:hotspots`, which compiles them on a live body and
// fails on any shader error the console reports.
const NAMES = ['rings', 'shards', 'wounds'];
const meshes = [...group.children];

// Fire one of each so the attribute arrays carry real values rather than the
// -1 lifespans they are seeded with, and so this page exercises the same code
// path a hit does.
//
// WITH AN ANCHOR, which is the whole reason this needs a stand-in shape: the
// wound refuses to place itself without one — a mark in world space is off the
// animal a frame later — so a contact carrying `sphere: null` fires the break
// and no wound at all, correctly, and this page would report the wound shader
// as never having run. The stub is the smallest thing hitShape.js's two
// conversions need: one sphere with a live matrix.
const stubShape = {
  alive: true,
  stamp: -1,
  visual: new THREE.Object3D(),
  spheres: [{
    // A rigid (unskinned) sphere, which is the branch that needs no bind
    // matrices — `mesh` only has to be something carrying a world matrix.
    mesh: new THREE.Object3D(),
    bone: null,
    cx: 0, cy: 0, cz: 0, r: 1,
    m: new THREE.Matrix4(), wx: 0, wy: 0, wz: 0, wr: 1,
  }],
};
spawnBossImpact(
  { x: 0, y: 0, nx: 0, ny: 1, sphere: stubShape.spheres[0], index: 0 },
  { scale: 1, shape: stubShape },
);
updateBossImpacts(0.016);

// three's own prefix, cut to what these shaders actually reference. Kept
// explicit rather than borrowed from the renderer: the point of this page is
// to be told what the DRIVER thinks, and a prefix generated by the same
// library that generated the shader can hide a mismatch between them.
const PREFIX_VERT = `precision highp float;
uniform mat4 modelViewMatrix;
uniform mat4 projectionMatrix;
attribute vec3 position;
attribute vec2 uv;
`;
const PREFIX_FRAG = `precision highp float;
`;

function liveCount(geo) {
  const life = geo.attributes.aLife;
  return life ? [...life.array].filter((v, k) => k % 4 === 0 && v >= 0).length : 0;
}

const cases = meshes.map((m, i) => {
  const declared = [...m.material.vertexShader.matchAll(/^\s*attribute\s+\w+\s+(\w+)\s*;/gm)].map((x) => x[1]);
  const supplied = Object.keys(m.geometry.attributes);
  return {
    name: NAMES[i] ?? `mesh${i}`,
    vertex: PREFIX_VERT + m.material.vertexShader,
    fragment: PREFIX_FRAG + m.material.fragmentShader,
    // The instanced attributes the vertex shader asks for, minus the two the
    // prefix above already provides.
    missing: declared.filter((a) => a !== 'position' && a !== 'uv' && !supplied.includes(a)),
    instances: m.geometry.instanceCount,
    // Proof the spawn above actually wrote something: an aLife.x of -1 is the
    // seeded "never born" value, so a live instance means the fire path ran.
    // Proof the spawn above actually wrote something: an aLife.x of -1 is the
    // seeded "never born" value, so a live instance means the fire path ran.
    live: liveCount(m.geometry),
  };
});

const OUT = process.argv[2] ?? path.join(
  path.dirname(fileURLToPath(import.meta.url)), '../.impact-shader-check.html',
);

const html = `<!doctype html><meta charset="utf-8"><title>boss impact shader check</title>
<body style="font:13px ui-monospace,monospace;background:#111;color:#ddd;padding:16px">
<pre id="out">compiling...</pre>
<script>
const CASES = ${JSON.stringify(cases)};
const gl = document.createElement('canvas').getContext('webgl');
const lines = [];
let bad = 0;

function compile(label, type, src) {
  const s = gl.createShader(type);
  gl.shaderSource(s, src);
  gl.compileShader(s);
  if (gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    lines.push('  ok   ' + label);
    return s;
  }
  bad++;
  lines.push('  FAIL ' + label);
  for (const l of (gl.getShaderInfoLog(s) || '').trim().split('\\n')) lines.push('         ' + l);
  return null;
}

if (!gl) {
  lines.push('no webgl context — nothing was checked');
  bad++;
} else {
  for (const c of CASES) {
    lines.push('');
    lines.push(c.name + '  (' + c.instances + ' instances, ' + c.live + ' live after one spawn)');
    const v = compile('vertex shader', gl.VERTEX_SHADER, c.vertex);
    const f = compile('fragment shader', gl.FRAGMENT_SHADER, c.fragment);
    if (v && f) {
      // LINKED, not just compiled. A varying declared differently on the two
      // sides compiles cleanly on both and fails only here.
      const p = gl.createProgram();
      gl.attachShader(p, v);
      gl.attachShader(p, f);
      gl.linkProgram(p);
      if (gl.getProgramParameter(p, gl.LINK_STATUS)) {
        lines.push('  ok   links');
      } else {
        bad++;
        lines.push('  FAIL links');
        for (const l of (gl.getProgramInfoLog(p) || '').trim().split('\\n')) lines.push('         ' + l);
      }
    }
    if (c.missing.length) {
      bad++;
      lines.push('  FAIL attributes with nothing behind them: ' + c.missing.join(', '));
    } else {
      lines.push('  ok   every declared attribute is supplied by the geometry');
    }
    if (c.live === 0) {
      bad++;
      lines.push('  FAIL nothing was alive after a spawn — the fire path wrote no instance');
    } else {
      lines.push('  ok   a spawn wrote live instances');
    }
  }
}

lines.push('');
lines.push(bad === 0 ? 'ALL GOOD' : bad + ' PROBLEM(S)');
document.getElementById('out').textContent = lines.join('\\n');
document.title = bad === 0 ? 'impact shaders ok' : 'impact shaders FAILED';
<\/script>
`;

fs.writeFileSync(OUT, html);
console.log(`wrote ${OUT}`);
console.log('serve the directory over http and open it — file:// will not execute.');
